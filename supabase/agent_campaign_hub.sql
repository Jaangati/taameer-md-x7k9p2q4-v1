-- TAAMEER Agent Campaign Hub — agent readiness, budgets, campaigns and secure credentials.
create or replace function public.agent_campaign_module_access()
returns boolean language sql stable security invoker set search_path = '' as $$
  select coalesce((select p.status='active' and coalesce(p.modules,'[]'::jsonb) ? 'agent-campaigns'
    from public.profiles p where p.id=(select auth.uid())),false);
$$;

create table if not exists public.agent_campaign_user_permissions (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  can_manage_budget boolean not null default false,
  can_manage_accounts boolean not null default true,
  can_view_credentials boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
