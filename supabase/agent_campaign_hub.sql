create or replace function public.touch_agent_campaign_updated_at()
returns trigger language plpgsql security invoker set search_path='' as $$ begin new.updated_at=now(); return new; end; $$;
do $$ declare t text; begin foreach t in array array['agent_campaign_user_permissions','agent_campaign_agents','agent_campaign_accounts','agent_campaign_months','agent_campaign_allocations','agent_campaign_campaigns'] loop
  execute format('drop trigger if exists %I on public.%I','touch_'||t,t);
  execute format('create trigger %I before update on public.%I for each row execute function public.touch_agent_campaign_updated_at()','touch_'||t,t);
end loop; end $$;

create or replace function public.agent_campaign_can_view_credentials()
returns boolean language sql stable security invoker set search_path='' as $$
  select (select public.agent_campaign_module_access()) and coalesce((select p.role='admin' or ap.can_view_credentials
    from public.profiles p left join public.agent_campaign_user_permissions ap on ap.user_id=p.id where p.id=(select auth.uid())),false);
$$;
create or replace function public.agent_campaign_can_manage_budget()
returns boolean language sql stable security invoker set search_path='' as $$
  select (select public.agent_campaign_module_access()) and coalesce((select p.role='admin' or ap.can_manage_budget
    from public.profiles p left join public.agent_campaign_user_permissions ap on ap.user_id=p.id where p.id=(select auth.uid())),false);
$$;

create or replace function public.agent_campaign_save_credential(p_account_id uuid,p_password text,p_login_email text default null,p_recovery_email text default null,p_recovery_phone text default null)
returns void language plpgsql security definer set search_path='' as $$
declare v_secret uuid; begin
  if (select auth.uid()) is null or not (select public.agent_campaign_can_view_credentials()) then raise exception 'Not authorized'; end if;
  if char_length(coalesce(p_password,''))<6 then raise exception 'Password must contain at least 6 characters'; end if;
  if not exists(select 1 from public.agent_campaign_accounts where id=p_account_id) then raise exception 'Account not found'; end if;
  select secret_id into v_secret from public.agent_campaign_credentials where account_id=p_account_id;
  if v_secret is null then
    select vault.create_secret(p_password,'agent-campaign-'||p_account_id::text,'TAAMEER Instagram account credential') into v_secret;
    insert into public.agent_campaign_credentials(account_id,secret_id,login_email,recovery_email,recovery_phone,updated_by)
    values(p_account_id,v_secret,nullif(btrim(p_login_email),''),nullif(btrim(p_recovery_email),''),nullif(btrim(p_recovery_phone),''),(select auth.uid()));
  else
    perform vault.update_secret(v_secret,p_password);
    update public.agent_campaign_credentials set login_email=nullif(btrim(p_login_email),''),recovery_email=nullif(btrim(p_recovery_email),''),recovery_phone=nullif(btrim(p_recovery_phone),''),last_rotated_at=now(),updated_by=(select auth.uid()),updated_at=now() where account_id=p_account_id;
  end if;
  update public.agent_campaign_accounts set credentials_saved=true,updated_by=(select auth.uid()) where id=p_account_id;
  insert into public.agent_campaign_credential_audit(account_id,actor_id,action) values(p_account_id,(select auth.uid()),'saved');
end; $$;

create or replace function public.agent_campaign_reveal_credential(p_account_id uuid)
returns table(login_email text,password text,recovery_email text,recovery_phone text,last_rotated_at timestamptz)
language plpgsql security definer set search_path='' as $$ begin
  if (select auth.uid()) is null or not (select public.agent_campaign_can_view_credentials()) then raise exception 'Not authorized'; end if;
  insert into public.agent_campaign_credential_audit(account_id,actor_id,action) values(p_account_id,(select auth.uid()),'revealed');
  return query select c.login_email,v.decrypted_secret,c.recovery_email,c.recovery_phone,c.last_rotated_at
    from public.agent_campaign_credentials c join vault.decrypted_secrets v on v.id=c.secret_id where c.account_id=p_account_id;
end; $$;

